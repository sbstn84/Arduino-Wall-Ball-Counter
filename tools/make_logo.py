#!/usr/bin/env python3
"""Turn a PNG into a logo.h header that the sketch serves as /logo.png.

    python3 tools/make_logo.py my_logo.png                    # writes wallball_web/logo.h
    python3 tools/make_logo.py my_logo.png --out other/logo.h

Tips: use a PNG with a transparent or black background and light colours
(the page background is black). About 300 px wide and under 20 kB is fine,
the Arduino has limited memory. logo.h is ignored by git.
"""
import argparse
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent
ap = argparse.ArgumentParser()
ap.add_argument("png")
ap.add_argument("--out", default=str(root / "wallball_web" / "logo.h"))
args = ap.parse_args()

data = pathlib.Path(args.png).read_bytes()
if data[:8] != b"\x89PNG\r\n\x1a\n":
    raise SystemExit("not a PNG file")
if len(data) > 30000:
    print("warning: the logo is %d bytes, consider a smaller image" % len(data))

lines = []
for i in range(0, len(data), 20):
    lines.append("  " + ", ".join("0x%02X" % b for b in data[i:i + 20]) + ",")
text = ("// Logo (PNG) - served at /logo.png. Generated by tools/make_logo.py\n"
        "#pragma once\n#include <stdint.h>\n#include <stddef.h>\n\n"
        "const uint8_t LOGO_PNG[] = {\n" + "\n".join(lines) + "\n};\n"
        "const size_t LOGO_PNG_LEN = sizeof(LOGO_PNG);\n")
pathlib.Path(args.out).write_text(text)
print("wrote %s (%d bytes of PNG)" % (args.out, len(data)))
